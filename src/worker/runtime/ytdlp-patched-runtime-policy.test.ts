import { describe, it, before, after } from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { parseYtdlpVersion, YTDLP_RUNTIME } from "./ytdlp-runtime.server.ts";

/**
 * VIDEOFETCH-LD3E-PINNED-YTDLP-PATCHED-RUNTIME-SOURCE-IMPLEMENTATION-001 — the
 * vendored patch, its builder and every place that pins them must agree.
 *
 * The Worker image builds its yt-dlp runtime from the upstream asset and the
 * two reviewed members in `vendor/yt-dlp/2026.08.19-videofetch-ld3e/`. The
 * digests below are written here as LITERALS on purpose: this file is an
 * independent witness of what was reviewed, so a change to a vendored file,
 * to the builder, to the manifest, to `YTDLP_RUNTIME` or to the Dockerfile
 * cannot pass unless it is made here as well, in the same reviewed commit.
 *
 * The last suite runs the builder itself. It needs the upstream asset and a
 * Python 3.9+ interpreter, so it runs only when
 * `VIDEOFETCH_UPSTREAM_YTDLP_ARTIFACT` names a copy whose SHA-256 is the
 * pinned upstream digest (and `VIDEOFETCH_PINNED_YTDLP_PYTHON` an
 * interpreter); otherwise it SKIPS and says why.
 */

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const PATCH_DIR = "vendor/yt-dlp/2026.08.19-videofetch-ld3e";
const at = (rel: string): string => join(ROOT, ...PATCH_DIR.split("/"), ...rel.split("/"));
const sha256 = (b: Buffer | string): string => createHash("sha256").update(b).digest("hex");
const gitBlob = (b: Buffer): string => createHash("sha1").update(Buffer.concat([Buffer.from(`blob ${b.length}\0`), b])).digest("hex");

// The reviewed values (PATCH-MANIFEST.json repeats them; so must everything else).
const IDENTITY = "2026.08.19+videofetch.ld3e1";
const UPSTREAM = { bytes: 3_072_469, sha256: "1fa6733c37ea6fb51c99ad8fe785e7b7e5f3246c9b980230329d4fb72ed8d4d6", inventory: "0ec4533e7517564a1c00676a1e06ec2764b8094874ce93c187252a322ab9b92b" };
const OUTPUT = { bytes: 3_088_241, sha256: "2dfa21ec04eebb61612e3e6eb5d24f13527264275a0a34d6ef7e5d33a9260259" };
const HTTP_PY = { bytes: 19_585, sha256: "657dae31370ae3b93c3071e80399195087dc3898fe41ce79e5c0b68720d0c75a", upstream: "e111fffdc894f68253ce3c5155fa1aa7390e58caa9a33eeb28d9ef78134e2cd0" };
const VERSION_PY = { bytes: 518, sha256: "108f4a37073c75f4610ce335e02740748a2f431f7d894026b32cd31feeebf92c", upstream: "5d7c9a50dbacbdb3596a77c9856a7c1aeded2ffce3cfdd25a7df76954791cf4d" };
const BUILDER_SHA256 = "8f828d06cf28f136cd337befc69ec4a828fa39f0d4b335b1803b01bdc2119126";
const LICENSE_GIT_BLOB = "68a49daad8ff7e35068f2b7a97d643aab440eaec";
const RELEASE_GIT_HEAD = "594bd50c2c78ac432f81600d309fdc4e0a92d82c";

/** The upstream `yt_dlp/version.py` member (git blob 9b3a255f…), exactly. */
const UPSTREAM_VERSION_PY = [
  "# Autogenerated by devscripts/update-version.py", "", "__version__ = '2026.08.19'", "",
  `RELEASE_GIT_HEAD = '${RELEASE_GIT_HEAD}'`, "", "VARIANT = None", "", "UPDATE_HINT = None", "",
  "CHANNEL = 'stable'", "", "ORIGIN = 'yt-dlp/yt-dlp'", "", "_pkg_version = '2026.08.19'", "",
].join("\n");

type Manifest = {
  identity: string;
  upstream: { release: string; releaseGitHead: string; assetUrl: string; assetBytes: number; assetSha256: string; archiveMembers: number; memberInventorySha256: string };
  replacedMembers: { member: string; upstreamSha256: string; replacement: string; replacementBytes: number; replacementSha256: string }[];
  builder: { file: string; sha256: string };
  output: { identity: string; bytes: number; sha256: string; installedAt: string };
  review: { laboratoryExecutableSha256: string };
};
const manifest = (): Manifest => JSON.parse(readFileSync(at("PATCH-MANIFEST.json"), "utf8")) as Manifest;

describe("LD-3e vendored patch: exact source identity", () => {
  it("vendors the reviewed http.py, byte for byte", () => {
    const b = readFileSync(at("yt_dlp/downloader/http.py"));
    assert.equal(b.length, HTTP_PY.bytes);
    assert.equal(sha256(b), HTTP_PY.sha256, "the replacement must be the independently accepted laboratory source");
  });

  it("vendors the identity member, which differs from upstream only in the identity", () => {
    const b = readFileSync(at("yt_dlp/version.py"));
    assert.equal(b.length, VERSION_PY.bytes);
    assert.equal(sha256(b), VERSION_PY.sha256);
    assert.equal(sha256(UPSTREAM_VERSION_PY), VERSION_PY.upstream, "the reconstructed upstream member is the pinned one");
    const ours = b.toString("utf8").split("\n");
    const theirs = UPSTREAM_VERSION_PY.split("\n");
    // Two added comment lines right after the upstream header, and two changed assignments.
    assert.deepEqual(ours.slice(0, 1), theirs.slice(0, 1));
    assert.ok(ours[1].startsWith("# VideoFetch downstream variant (LD-3e)") && ours[2].startsWith("# replacement, yt_dlp/downloader/http.py."));
    const rest = ours.slice(3);
    assert.equal(rest.length, theirs.length - 1);
    const changed = rest.map((line, i) => [theirs[i + 1], line]).filter(([a, b2]) => a !== b2);
    assert.deepEqual(changed, [
      ["__version__ = '2026.08.19'", `__version__ = '${IDENTITY}'`],
      ["_pkg_version = '2026.08.19'", `_pkg_version = '${IDENTITY}'`],
    ]);
  });

  it("vendors the reviewed builder", () => {
    assert.equal(sha256(readFileSync(at("build_patched_ytdlp.py"))), BUILDER_SHA256);
  });

  it("keeps the upstream licence text", () => {
    const text = readFileSync(at("LICENSE"));
    assert.equal(gitBlob(text), LICENSE_GIT_BLOB, "the upstream LICENSE at the release tag");
    assert.ok(text.toString("utf8").startsWith("This is free and unencumbered software released into the public domain."));
  });

  it("holds exactly the approved files, and nothing else", () => {
    const files: string[] = [];
    const walk = (abs: string): void => {
      for (const e of readdirSync(abs, { withFileTypes: true })) {
        const p = join(abs, e.name);
        if (e.isDirectory()) walk(p);
        else files.push(relative(join(ROOT, ...PATCH_DIR.split("/")), p).split("\\").join("/"));
      }
    };
    walk(join(ROOT, ...PATCH_DIR.split("/")));
    assert.deepEqual(files.sort(), [
      "LICENSE", "PATCH-MANIFEST.json", "PROVENANCE.md", "build_patched_ytdlp.py", "yt_dlp/downloader/http.py", "yt_dlp/version.py",
    ]);
    const vendor = readdirSync(join(ROOT, "vendor"));
    assert.deepEqual(vendor, ["yt-dlp"]);
    assert.deepEqual(readdirSync(join(ROOT, "vendor", "yt-dlp")), ["2026.08.19-videofetch-ld3e"]);
  });

  it("protects the vendored bytes from line-ending conversion", () => {
    const attributes = readFileSync(join(ROOT, ".gitattributes"), "utf8").split("\n").filter((l) => l && !l.startsWith("#"));
    assert.ok(attributes.includes("vendor/yt-dlp/** -text"));
  });
});

describe("LD-3e vendored patch: every pin agrees", () => {
  it("the manifest states the reviewed values", () => {
    const m = manifest();
    assert.equal(m.identity, IDENTITY);
    assert.deepEqual(
      { r: m.upstream.release, h: m.upstream.releaseGitHead, b: m.upstream.assetBytes, s: m.upstream.assetSha256, n: m.upstream.archiveMembers, i: m.upstream.memberInventorySha256 },
      { r: "2026.08.19", h: RELEASE_GIT_HEAD, b: UPSTREAM.bytes, s: UPSTREAM.sha256, n: 1053, i: UPSTREAM.inventory },
    );
    assert.deepEqual(m.replacedMembers.map((r) => [r.member, r.replacement, r.upstreamSha256, r.replacementSha256, r.replacementBytes]), [
      ["yt_dlp/version.py", "yt_dlp/version.py", VERSION_PY.upstream, VERSION_PY.sha256, VERSION_PY.bytes],
      ["yt_dlp/downloader/http.py", "yt_dlp/downloader/http.py", HTTP_PY.upstream, HTTP_PY.sha256, HTTP_PY.bytes],
    ]);
    assert.deepEqual([m.builder.file, m.builder.sha256], ["build_patched_ytdlp.py", BUILDER_SHA256]);
    assert.deepEqual([m.output.identity, m.output.bytes, m.output.sha256], [IDENTITY, OUTPUT.bytes, OUTPUT.sha256]);
    assert.notEqual(m.output.sha256, m.review.laboratoryExecutableSha256, "the identity member makes the release artifact a new file");
  });

  it("the runtime module pins the same upstream asset, the same output and the same identity", () => {
    assert.equal(YTDLP_RUNTIME.expectedVersion, IDENTITY);
    assert.equal(YTDLP_RUNTIME.sha256, OUTPUT.sha256);
    assert.equal(YTDLP_RUNTIME.sizeBytes, OUTPUT.bytes);
    assert.equal(YTDLP_RUNTIME.upstream.sha256, UPSTREAM.sha256);
    assert.equal(YTDLP_RUNTIME.upstream.version, "2026.08.19");
    assert.equal(YTDLP_RUNTIME.upstream.releaseUrl, manifest().upstream.assetUrl);
    assert.equal(YTDLP_RUNTIME.artifactPath, manifest().output.installedAt);
  });

  it("the builder pins the same values", () => {
    const b = readFileSync(at("build_patched_ytdlp.py"), "utf8");
    const num = (name: string): number => Number(new RegExp(`^${name} = (\\d+)$`, "m").exec(b)?.[1]);
    const str = (name: string): string | undefined => new RegExp(`^${name} = "([0-9a-f]{64})"$`, "m").exec(b)?.[1];
    assert.equal(num("UPSTREAM_BYTES"), UPSTREAM.bytes);
    assert.equal(str("UPSTREAM_SHA256"), UPSTREAM.sha256);
    assert.equal(num("MEMBER_COUNT"), 1053);
    assert.equal(str("UPSTREAM_INVENTORY_SHA256"), UPSTREAM.inventory);
    assert.equal(num("OUTPUT_BYTES"), OUTPUT.bytes);
    assert.equal(str("OUTPUT_SHA256"), OUTPUT.sha256);
    const replacements = [...b.matchAll(/\("(yt_dlp\/[a-z_/]+\.py)",\s*"([0-9a-f]{64})",\s*"([0-9a-f]{64})"\)/g)].map((m) => [m[1], m[2], m[3]]);
    assert.deepEqual(replacements, [
      ["yt_dlp/version.py", VERSION_PY.upstream, VERSION_PY.sha256],
      ["yt_dlp/downloader/http.py", HTTP_PY.upstream, HTTP_PY.sha256],
    ]);
  });

  it("the Dockerfile builds from the vendored directory and checks the same output digest", () => {
    const dockerfile = readFileSync(join(ROOT, "Dockerfile.worker"), "utf8");
    assert.ok(dockerfile.includes(`COPY ${PATCH_DIR}/ /build/patch/`));
    assert.ok(dockerfile.includes(`echo "${OUTPUT.sha256}  /build/out/yt-dlp" | sha256sum --check --strict -`));
    assert.ok(dockerfile.includes(`ADD --checksum=sha256:${UPSTREAM.sha256} \\`));
  });

  it("the identity is distinct, parseable and a PEP 440 local version", () => {
    assert.notEqual(IDENTITY, "2026.08.19", "the unmodified upstream artifact prints 2026.08.19 and must be refused");
    assert.equal(parseYtdlpVersion(`${IDENTITY}\n`), IDENTITY);
    // PEP 440: a release segment, then `+` and a local label of lower-case alphanumeric segments.
    assert.match(IDENTITY, /^(?<release>\d+(\.\d+)*)\+(?<local>[a-z0-9]+(\.[a-z0-9]+)*)$/);
    // Upstream nightly builds print digits only (`2026.08.19.123456`): none can collide with a `+` label.
    assert.equal(/^\d{4}\.\d{2}\.\d{2}(\.\d+)?$/.test(IDENTITY), false);
  });
});

// ── the builder itself, on the real upstream asset ─────────────────────────────

const UPSTREAM_COPY = process.env.VIDEOFETCH_UPSTREAM_YTDLP_ARTIFACT || "";
const PYTHON = process.env.VIDEOFETCH_PINNED_YTDLP_PYTHON || "";
function builderGate(): string | null {
  if (!UPSTREAM_COPY || !existsSync(UPSTREAM_COPY)) return "no upstream yt-dlp 2026.08.19 copy (VIDEOFETCH_UPSTREAM_YTDLP_ARTIFACT)";
  if (!PYTHON || !existsSync(PYTHON)) return "no interpreter (VIDEOFETCH_PINNED_YTDLP_PYTHON)";
  if (sha256(readFileSync(UPSTREAM_COPY)) !== UPSTREAM.sha256) return "the upstream copy is not the pinned asset";
  return null;
}
const GATE = builderGate();
const skip = GATE === null ? false : `SKIPPED — ${GATE}`;

describe("LD-3e builder: deterministic, verified, fail-closed", { skip, timeout: 300_000 }, () => {
  let work = "";
  before(() => {
    work = mkdtempSync(join(tmpdir(), "ytdlp-builder-"));
  });
  after(() => rmSync(work, { recursive: true, force: true }));

  /** Runs a builder exactly as the Dockerfile does: `python3 -I -B <builder> <upstream> <output>`, from an unrelated directory. */
  function build(builderDir: string, upstream: string, output: string) {
    const r = spawnSync(PYTHON, ["-I", "-B", join(builderDir, "build_patched_ytdlp.py"), upstream, output], {
      cwd: work, encoding: "utf8", timeout: 120_000, env: { PATH: "/usr/bin:/bin", LC_ALL: "C" },
    });
    return { code: r.status, stdout: r.stdout, stderr: r.stderr, written: existsSync(output) };
  }
  /** A copy of the vendored directory with one planted change, so the committed files are never touched. */
  function patchCopy(name: string, plant: (copy: string) => void): string {
    const copy = join(work, name);
    cpSync(join(ROOT, ...PATCH_DIR.split("/")), copy, { recursive: true });
    plant(copy);
    return copy;
  }
  function plantedUpstream(name: string, change: (b: Buffer) => Buffer): string {
    const p = join(work, `${name}.upstream`);
    writeFileSync(p, change(readFileSync(UPSTREAM_COPY)));
    return p;
  }
  const pin = (builder: string, constant: string, value: string | number): void => {
    const file = join(builder, "build_patched_ytdlp.py");
    const text = readFileSync(file, "utf8");
    const re = new RegExp(`^${constant} = .*$`, "m");
    assert.ok(re.test(text), `the builder copy has ${constant}`);
    writeFileSync(file, text.replace(re, `${constant} = ${typeof value === "number" ? value : JSON.stringify(value)}`));
  };
  const committed = join(ROOT, ...PATCH_DIR.split("/"));

  it("builds exactly the pinned artifact, and writes nothing else", () => {
    const before = readdirSync(committed, { recursive: true }).sort();
    const out = join(work, "out-1");
    const r = build(committed, UPSTREAM_COPY, out);
    assert.equal(r.code, 0, r.stderr);
    const bytes = readFileSync(out);
    assert.equal(bytes.length, YTDLP_RUNTIME.sizeBytes);
    assert.equal(sha256(bytes), YTDLP_RUNTIME.sha256);
    assert.equal(statSync(out).mode & 0o222, 0, "the output is created read-only");
    assert.deepEqual(readdirSync(committed, { recursive: true }).sort(), before, "no bytecode or other file appears next to the builder");
  });

  it("is deterministic: a second build is byte-identical", () => {
    const a = join(work, "out-2a");
    const b = join(work, "out-2b");
    assert.equal(build(committed, UPSTREAM_COPY, a).code, 0);
    assert.equal(build(committed, UPSTREAM_COPY, b).code, 0);
    assert.ok(readFileSync(a).equals(readFileSync(b)));
  });

  const refusals: { name: string; check: string; setup: () => { builder: string; upstream: string; output?: string } }[] = [
    { name: "one byte of the upstream asset changed", check: "upstream digest",
      setup: () => ({ builder: committed, upstream: plantedUpstream("r1", (b) => { const c = Buffer.from(b); c[1_000_000] ^= 1; return c; }) }) },
    { name: "one byte of the replacement http.py changed", check: "replacement digest",
      setup: () => ({ builder: patchCopy("r2", (c) => { const f = join(c, "yt_dlp", "downloader", "http.py"); const b = readFileSync(f); b[100] ^= 1; writeFileSync(f, b); }), upstream: UPSTREAM_COPY }) },
    { name: "the identity member changed", check: "replacement digest",
      setup: () => ({ builder: patchCopy("r3", (c) => { const f = join(c, "yt_dlp", "version.py"); writeFileSync(f, readFileSync(f, "utf8").replaceAll("ld3e1", "ld3e2")); }), upstream: UPSTREAM_COPY }) },
    { name: "the output path already exists", check: "output path",
      setup: () => { const o = join(work, "r4-existing"); writeFileSync(o, "x"); return { builder: committed, upstream: UPSTREAM_COPY, output: o }; } },
    { name: "the pinned output digest is not what the inputs produce", check: "output verification",
      setup: () => ({ builder: patchCopy("r5", (c) => pin(c, "OUTPUT_SHA256", "0".repeat(64))), upstream: UPSTREAM_COPY }) },
    { name: "a byte after the end record (with the upstream pins moved to match)", check: "archive structure",
      setup: () => {
        const up = plantedUpstream("r6", (b) => Buffer.concat([b, Buffer.from([0])]));
        const builder = patchCopy("r6", (c) => { pin(c, "UPSTREAM_BYTES", UPSTREAM.bytes + 1); pin(c, "UPSTREAM_SHA256", sha256(readFileSync(up))); });
        return { builder, upstream: up };
      } },
    { name: "a member's timestamp changed (with the upstream digest moved to match)", check: "member metadata",
      setup: () => {
        const up = plantedUpstream("r7", (b) => {
          const c = Buffer.from(b);
          const cd = c.lastIndexOf(Buffer.from("PK\x01\x02", "latin1")); // the last central record
          c.writeUInt16LE(c.readUInt16LE(cd + 12) ^ 1, cd + 12); // its modification time
          return c;
        });
        return { builder: patchCopy("r7", (c) => pin(c, "UPSTREAM_SHA256", sha256(readFileSync(up)))), upstream: up };
      } },
  ];
  for (const r of refusals) {
    it(`refuses, writing nothing: ${r.name}`, () => {
      const { builder, upstream, output } = r.setup();
      const out = output ?? join(work, `out-${r.check.replace(/\s+/g, "-")}-${Math.random().toString(16).slice(2)}`);
      const existed = existsSync(out);
      const result = build(builder, upstream, out);
      assert.equal(result.code, 1, `exit status 1 (${result.stderr.trim()})`);
      assert.ok(result.stderr.startsWith(`REFUSED ${r.check}: `), `refused by the "${r.check}" check, not another: ${result.stderr.trim()}`);
      assert.equal(result.stdout, "");
      if (!existed) assert.equal(existsSync(out), false, "nothing is written");
    });
  }
});
