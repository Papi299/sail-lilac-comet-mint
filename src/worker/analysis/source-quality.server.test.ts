function expectedSummary(name: string): SourceQuality {
  const e = EXPECTED[name];
  assert.ok(e, `${name}: this scenario has no expected summary`);
  return {
    observedMaxHeight: e.observed,
    deliverableMaxHeight: e.deliverable,
    withheld: e.withheld.map(([reason, count, maxObservedHeight]) => ({
      reason: reason as SourceQuality["withheld"][number]["reason"],
      count,
      maxObservedHeight,
    })),
    protectedUnenumerated: e.protectedUnenumerated ?? false,
    maybeProtectedObserved: e.maybeProtectedObserved ?? false,
  };
}

