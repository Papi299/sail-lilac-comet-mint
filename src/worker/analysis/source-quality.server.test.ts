const TESTDATA = join(import.meta.dirname, "testdata");
const SAFE_URL = "https://example.invalid/watch/abc";

type Scenario = {
  readonly name: string;
  readonly ffmpegAvailable: boolean;
  readonly maxFileSizeBytes: number;
  readonly document?: Record<string, unknown>;
  readonly fixture?: string;
};

type GoldenEntry = {
  readonly ok: boolean;
  readonly code?: string;
  readonly video?: Record<string, unknown>;
  readonly selections?: Record<string, unknown>;
  readonly plans?: Record<string, unknown>;
  readonly selectors?: Record<string, string[]>;
};

const CORPUS = JSON.parse(
  readFileSync(join(TESTDATA, "source-quality-corpus.json"), "utf8"),
) as Scenario[];

const GOLDEN = JSON.parse(
  readFileSync(join(TESTDATA, "source-quality-preset-identity.golden.json"), "utf8"),
) as Record<string, GoldenEntry>;

function documentOf(scenario: Scenario): Record<string, unknown> {
  if (scenario.document) return scenario.document;
  assert.ok(scenario.fixture, `${scenario.name}: a scenario needs a document or a fixture`);
  return JSON.parse(readFileSync(join(TESTDATA, scenario.fixture), "utf8")) as Record<string, unknown>;
}

/** Runs the real internal analyzer over one scenario with a canned yt-dlp result. */
async function analyzeScenario(scenario: Scenario) {
  return analyzeGenericMediaInternal(SAFE_URL, {
    limits: {
      analysisTimeoutSeconds: 45,
      maxVideoDurationSeconds: 7200,
      maxFileSizeBytes: scenario.maxFileSizeBytes,
    },
    ffmpegAvailable: scenario.ffmpegAvailable,
    runner: async () => ({ code: 0, stdout: JSON.stringify(documentOf(scenario)), stderr: "" }),
    probeRuntime: async () => ({ available: true, version: "2026.08.19", reason: "ok" as const }),
    validateUrl: async (raw: string) => ({ url: raw, hostname: new URL(raw).hostname }),
  });
}

function sourceQualityOf(video: { sourceQuality?: SourceQuality }): SourceQuality {
  assert.ok(video.sourceQuality, "generic analysis must report sourceQuality");
  return video.sourceQuality;
}

