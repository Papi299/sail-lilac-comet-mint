describe("P1 rendition inventory: protection signals", () => {
  const baseFormats: Array<Record<string, unknown>> = [
    { format_id: "p720", ext: "mp4", protocol: "https", height: 720, vcodec: "avc1.640028", acodec: "mp4a.40.2", video_ext: "mp4", audio_ext: "none", filesize: 1024 },
  ];
  const run = async (document: Record<string, unknown>) =>
    analyzeGenericMediaInternal(SAFE_URL, {
      limits: { analysisTimeoutSeconds: 45, maxVideoDurationSeconds: 7200, maxFileSizeBytes: 4 * 1024 ** 3 },
      ffmpegAvailable: true,
      runner: async () => ({ code: 0, stdout: JSON.stringify(document), stderr: "" }),
      probeRuntime: async () => ({ available: true, version: "2026.08.19", reason: "ok" as const }),
      validateUrl: async (raw: string) => ({ url: raw, hostname: new URL(raw).hostname }),
    });
  const doc = (extra: Record<string, unknown> = {}, formats = baseFormats) => ({
    _type: "video",
    title: "Protection",
    duration: 60,
    formats,
    ...extra,
  });

  it("a stripped-protected document reports existence, never an invented height", async () => {
    const { video } = await run(doc({ _has_drm: true }));
    const quality = sourceQualityOf(video);
    assert.equal(quality.protectedUnenumerated, true);
    // The clear ladder's own maximum, and nothing above it.
    assert.equal(quality.observedMaxHeight, 720);
    assert.equal(quality.deliverableMaxHeight, 720);
    assert.deepEqual(quality.withheld, []);
  });

  it("only an exact `true` means renditions were stripped", async () => {
    for (const signal of [false, null, "true", 1, "maybe", undefined, {}]) {
      const { video } = await run(doc(signal === undefined ? {} : { _has_drm: signal }));
      assert.equal(
        sourceQualityOf(video).protectedUnenumerated,
        false,
        `_has_drm=${JSON.stringify(signal)} must not claim stripped renditions`,
      );
    }
  });

  it("a `maybe` marker is recorded and changes nothing about delivery", async () => {
    const plain = await run(doc());
    const marked = await run(doc({}, [{ ...baseFormats[0]!, has_drm: "maybe" }]));

    assert.equal(sourceQualityOf(plain.video).maybeProtectedObserved, false);
    assert.equal(sourceQualityOf(marked.video).maybeProtectedObserved, true);

    // Delivery is byte-identical: same presets, same selections.
    assert.deepEqual(marked.video.presets, plain.video.presets);
    assert.deepEqual(marked.selections, plain.selections);
    assert.equal(sourceQualityOf(marked.video).deliverableMaxHeight, 720);
  });

  it("an unparseable protection value never fails the analysis", async () => {
    for (const signal of [{ nested: true }, ["array"], 42]) {
      const { video } = await run(doc({ _has_drm: signal }, [{ ...baseFormats[0]!, has_drm: signal }]));
      assert.equal(video.presets.length > 0, true, "a weird marker must not reduce capability");
      assert.equal(sourceQualityOf(video).maybeProtectedObserved, false);
    }
  });
});

describe("P1 rendition inventory: the public summary leaks nothing", () => {
  const SENTINEL = "SUPER_SECRET_VALUE";

  it("upstream strings never reach sourceQuality, the body, or an error", async () => {
    const document = {
      _type: "video",
      title: `A video ${SENTINEL}`,
      duration: 60,
      formats: [
        { format_id: "p720", ext: "mp4", protocol: "https", height: 720, vcodec: "avc1.640028", acodec: "mp4a.40.2", video_ext: "mp4", audio_ext: "none", filesize: 2048 },
        {
          format_id: `id-${SENTINEL}`,
          ext: `mov-${SENTINEL}`,
          protocol: "https",
          height: 1080,
          vcodec: `codec-${SENTINEL}`,
          acodec: `acodec-${SENTINEL}`,
          video_ext: `mov-${SENTINEL}`,
          format_note: `note-${SENTINEL}`,
          url: `https://cdn.example.invalid/${SENTINEL}.mp4`,
          manifest_url: `https://cdn.example.invalid/${SENTINEL}.m3u8`,
          http_headers: { Cookie: SENTINEL },
        },
        {
          format_id: `manifest-${SENTINEL}`,
          ext: "mp4",
          protocol: `proto-${SENTINEL}`,
          height: 900,
          vcodec: "avc1.640028",
          acodec: `acodec-${SENTINEL}`,
          video_ext: "mp4",
          audio_ext: "none",
          manifest_url: `https://cdn.example.invalid/${SENTINEL}.mpd`,
        },
      ],
    };

    const logged: string[] = [];
    const streams = [process.stdout, process.stderr] as const;
    const originals = streams.map((s) => s.write.bind(s));
    const console_ = { log: console.log, warn: console.warn, error: console.error, info: console.info, debug: console.debug };
    streams.forEach((s) => {
      s.write = ((chunk: unknown) => {
        logged.push(String(chunk));
        return true;
      }) as typeof s.write;
    });
    for (const key of Object.keys(console_) as Array<keyof typeof console_>) {
      console[key] = ((...args: unknown[]) => logged.push(args.map(String).join(" "))) as never;
    }

    try {
      const { video } = await analyzeGenericMediaInternal(SAFE_URL, {
        limits: { analysisTimeoutSeconds: 45, maxVideoDurationSeconds: 7200, maxFileSizeBytes: 4 * 1024 ** 3 },
        ffmpegAvailable: true,
        runner: async () => ({ code: 0, stdout: JSON.stringify(document), stderr: "" }),
        probeRuntime: async () => ({ available: true, version: "2026.08.19", reason: "ok" as const }),
        validateUrl: async (raw: string) => ({ url: raw, hostname: new URL(raw).hostname }),
      });

      const quality = sourceQualityOf(video);
      // The unsupported rendition WAS observed and classified...
      assert.equal(quality.observedMaxHeight, 1080);
      assert.equal(quality.deliverableMaxHeight, 720);
      assert.deepEqual(quality.withheld, [
        { reason: "unsupported_protocol", count: 1, maxObservedHeight: 900 },
        { reason: "unsupported_container", count: 1, maxObservedHeight: 1080 },
      ]);
      // ...without carrying any of its strings.
      assert.equal(JSON.stringify(quality).includes(SENTINEL), false);
      for (const entry of quality.withheld) {
        assert.ok((SOURCE_QUALITY_WITHHELD_REASONS as readonly string[]).includes(entry.reason));
      }
      assert.equal(
        JSON.stringify({ ...video, title: "" }).includes(SENTINEL),
        false,
        "only the sanitized title may ever carry upstream text",
      );
    } finally {
      streams.forEach((s, i) => {
        s.write = originals[i]!;
      });
      Object.assign(console, console_);
    }

    assert.equal(logged.join("").includes(SENTINEL), false, "nothing upstream may be logged");
  });

  it("a summary is made only of numbers, booleans and vocabulary values", async () => {
    const scenario = CORPUS.find((s) => s.name === "case11-not-selected-within-rung")!;
    const { video } = await analyzeScenario(scenario);
    const quality = sourceQualityOf(video);

    assert.deepEqual(Object.keys(quality).sort(), [
      "deliverableMaxHeight",
      "maybeProtectedObserved",
      "observedMaxHeight",
      "protectedUnenumerated",
      "withheld",
    ]);
    for (const entry of quality.withheld) {
      assert.deepEqual(Object.keys(entry).sort(), ["count", "maxObservedHeight", "reason"]);
      assert.equal(typeof entry.count, "number");
      assert.ok((SOURCE_QUALITY_WITHHELD_REASONS as readonly string[]).includes(entry.reason));
    }
  });
});

describe("P1 rendition inventory: bounds", () => {
  it("the public count bound covers the analyzer's own raw-format ceiling", () => {
    assert.ok(YTDLP_ANALYSIS_MAX_RAW_FORMATS <= SOURCE_QUALITY_MAX_COUNT);
  });

  it("a very wide ladder aggregates into ONE bounded entry", () => {
    const formats = Array.from({ length: YTDLP_ANALYSIS_MAX_RAW_FORMATS }, (_, i) => ({
      format_id: `hls-${i}`,
      ext: "mp4",
      protocol: "m3u8_native",
      height: 240 + (i % 8) * 120,
      vcodec: "avc1.640028",
      acodec: "mp4a.40.2",
      video_ext: "mp4",
      audio_ext: "none",
    }));
    const { build, inventory } = analyzeGenericFormats(formats, {
      ffmpegAvailable: true,
      maxFileSizeBytes: 4 * 1024 ** 3,
    });
    const quality = summarizeSourceQuality(inventory);

    assert.deepEqual(build.presets, []);
    assert.equal(inventory.renditions.length, YTDLP_ANALYSIS_MAX_RAW_FORMATS);
    assert.equal(quality.withheld.length, 1);
    assert.deepEqual(quality.withheld[0], {
      reason: "unsupported_protocol",
      count: YTDLP_ANALYSIS_MAX_RAW_FORMATS,
      maxObservedHeight: 1080,
    });
    assert.ok(JSON.stringify(quality).length < 400, "the public summary stays tiny");
    assert.deepEqual(SourceQualitySchema.parse(quality), quality);
  });

  it("a height above the public bound is not a fact", () => {
    const tall = (height: number) => ({
      format_id: "p",
      ext: "mp4",
      protocol: "https",
      height,
      vcodec: "avc1.640028",
      acodec: "mp4a.40.2",
      video_ext: "mp4",
      audio_ext: "none",
    });
    const at = summarizeSourceQuality(
      analyzeGenericFormats([tall(SOURCE_QUALITY_MAX_HEIGHT)], { ffmpegAvailable: true, maxFileSizeBytes: 4 * 1024 ** 3 }).inventory,
    );
    assert.equal(at.observedMaxHeight, SOURCE_QUALITY_MAX_HEIGHT);

    const over = summarizeSourceQuality(
      analyzeGenericFormats([tall(SOURCE_QUALITY_MAX_HEIGHT + 1)], { ffmpegAvailable: true, maxFileSizeBytes: 4 * 1024 ** 3 }).inventory,
    );
    assert.equal(over.observedMaxHeight, null, "an implausible height is dropped, never clamped");
    assert.equal(over.deliverableMaxHeight, null);
  });
});

describe("P1 rendition inventory: what counts as an observed video rendition", () => {
  const analyze = (formats: Array<Record<string, unknown>>) =>
    analyzeGenericFormats(formats, { ffmpegAvailable: true, maxFileSizeBytes: 4 * 1024 ** 3 });

  it("audio-only, storyboard, image and subtitle rows never inflate the observed height", () => {
    const junk = [
      { format_id: "sb", ext: "mhtml", protocol: "mhtml", height: 2160, vcodec: "none", acodec: "none", video_ext: "none", audio_ext: "none", format_note: "storyboard" },
      { format_id: "img", ext: "jpg", protocol: "https", height: 4320, vcodec: null, acodec: null, video_ext: "jpg", audio_ext: "none" },
      { format_id: "sub", ext: "vtt", protocol: "https", height: 4320, vcodec: null, acodec: null, video_ext: "vtt", audio_ext: "none" },
      { format_id: "aud", ext: "m4a", protocol: "https", height: 9999, vcodec: "none", acodec: "mp4a.40.2", video_ext: "none", audio_ext: "m4a" },
      { format_id: "prev", ext: "mp4", protocol: "https", height: 4320, vcodec: "avc1.4d401f", acodec: "none", video_ext: "mp4", audio_ext: "none", format_note: "preview image" },
    ];
    const { inventory } = analyze(junk);
    assert.deepEqual(inventory.renditions, []);
    assert.equal(summarizeSourceQuality(inventory).observedMaxHeight, null);
  });

  it("a named video codec is video evidence; an unknown codec needs a coherent container", () => {
    const { inventory } = analyze([
      { format_id: "codec", ext: "mkv", protocol: "https", height: 1080, vcodec: "avc1.640028", acodec: "mp4a.40.2", video_ext: "mkv", audio_ext: "none" },
      { format_id: "shape", ext: "mov", protocol: "https", height: 720, vcodec: null, acodec: null, video_ext: "mov", audio_ext: "none" },
      { format_id: "incoherent", ext: "mp4", protocol: "https", height: 2160, vcodec: null, acodec: null, video_ext: "webm", audio_ext: "none" },
    ]);
    assert.deepEqual(
      inventory.renditions.map((r) => [r.observed.height, r.observed.videoEvidence, r.observed.container]),
      [
        [1080, "codec", "mkv"],
        [720, "shape", "mov"],
      ],
    );
  });

  it("observed facts are closed values: protocol family, container, size state", () => {
    const { inventory } = analyze([
      { format_id: "a", ext: "mp4", protocol: "https", height: 720, vcodec: "avc1.640028", acodec: "mp4a.40.2", video_ext: "mp4", audio_ext: "none", filesize: 10 },
      { format_id: "b", ext: "mp4", protocol: "m3u8_native", height: 1080, vcodec: "avc1.640028", acodec: "none", video_ext: "mp4", audio_ext: "none", filesize_approx: 10 },
      { format_id: "c", ext: "mp4", protocol: "http_dash_segments", height: 1440, vcodec: "avc1.640028", acodec: "none", video_ext: "mp4", audio_ext: "none" },
      { format_id: "d", ext: "mp4", protocol: "rtmp", height: 240, vcodec: "avc1.640028", acodec: "none", video_ext: "mp4", audio_ext: "none" },
      { format_id: "e", ext: "mp4", height: 360, vcodec: "avc1.640028", acodec: "none", video_ext: "mp4", audio_ext: "none" },
    ]);
    assert.deepEqual(
      inventory.renditions.map((r) => [r.observed.protocol, r.observed.size]),
      [
        ["progressive", "exact"],
        ["hls", "estimated"],
        ["dash-segmented", "unknown"],
        ["other", "unknown"],
        ["unknown", "unknown"],
      ],
    );
  });

  it("every advertised video preset is backed by a rendition marked deliverable", async () => {
    for (const scenario of CORPUS) {
      const { video, selections, hlsSelections } = await analyzeScenario(scenario);
      const { inventory } = analyzeGenericFormats(
        (documentOf(scenario).formats ?? []) as never,
        {
          ffmpegAvailable: scenario.ffmpegAvailable,
          maxFileSizeBytes: scenario.maxFileSizeBytes,
        },
      );
      const deliverable = inventory.renditions.filter((r) => r.disposition === "deliverable");
      const videoPresets = video.presets.filter((p) => p.hasVideo);
      // HLS-7: an HLS-owned preset names its rendition by playlist location.
      // The corpus gives every admitted HLS row a distinct URL, so distinct
      // locations are distinct renditions here.
      const videoSources = new Set(
        videoPresets.map((p) => {
          const hls = hlsSelections[p.id];
          if (hls) return `hls:${hls.playlistUrl}`;
          const value = selections[p.id]!;
          return value.kind === "single" ? value.source.formatId : value.pair.video.formatId;
        }),
      );
      assert.equal(
        deliverable.length,
        videoSources.size,
        `${scenario.name}: one deliverable rendition per distinct advertised video source`,
      );
    }
  });
});

